class Command(BaseCommand):
    help = "Заполняет каталог услуг: 3 категории по 5 элементов"

    def handle(self, *args, **options):
        self._ensure_demo_admin()
        if CatalogItem.objects.exists():
            self.stdout.write("Каталог уже заполнен, пропускаю.")
            return

        for category_data in CATEGORIES:
            category = Category.objects.create(
                name=category_data["name"],
                description=category_data["description"],
            )
            for item in category_data["items"]:
                CatalogItem.objects.create(
                    category=category,
                    name=item["name"],
                    short_description=item["short_description"],
                    full_description=item["full_description"],
                    price=item["price"],
                    image=item["image"],
                )
        self.stdout.write(self.style.SUCCESS("Каталог заполнен: 3 категории, 15 услуг."))

    def _ensure_demo_admin(self):
        """Отдельный суперпользователь для проверки форм каталога. Пароль существующего admin не меняется."""
        if User.objects.filter(username="catalog").exists():
            return
        User.objects.create_superuser("catalog", "catalog@psi-expert.local", "catalog123")
        self.stdout.write("Создан администратор catalog / catalog123")
